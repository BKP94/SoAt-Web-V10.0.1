"""สร้าง Bootstrap Icons ฉบับ subset ให้ scCenter (เฉพาะ icon ที่หน้าใช้จริง)

ชุดเต็ม (css 84KB + woff2 127KB) เก็บไว้ที่โฟลเดอร์นี้เป็น source — ไม่ถูก serve
ผลลัพธ์เขียนทับ wwwroot/icons/bootstrap-icons.min.css + fonts/bootstrap-icons.woff2

เพิ่ม icon ใหม่ใน .razor/.cs (class "bi bi-xxx") แล้วต้องรันใหม่:
    pip install fonttools brotli
    python scCenter/tools/bootstrap-icons/subset.py
"""
import hashlib
import pathlib
import re
import sys

from fontTools import subset

HERE = pathlib.Path(__file__).resolve().parent
APP = HERE.parent.parent
OUT_CSS = APP / "wwwroot/icons/bootstrap-icons.min.css"
OUT_FONT = APP / "wwwroot/icons/fonts/bootstrap-icons.woff2"

full_css = (HERE / "bootstrap-icons.min.css").read_text(encoding="utf-8")
glyphs = dict(re.findall(r'\.bi-([a-z0-9-]+)::before\{content:"\\([0-9a-f]+)"\}', full_css))

used = set()
for src in (APP / "Components").rglob("*"):
    if src.suffix in (".razor", ".cs"):
        used.update(re.findall(r"\bbi-([a-z0-9]+(?:-[a-z0-9]+)*)", src.read_text(encoding="utf-8")))

missing = sorted(used - glyphs.keys())
if missing:
    sys.exit("ไม่พบ icon ใน Bootstrap Icons: " + ", ".join(missing))

names = sorted(used)
opts = subset.Options()
opts.flavor = "woff2"
opts.layout_features = []
opts.name_IDs = ["*"]  # เก็บ name table ไว้ (มีข้อความ license MIT)
font = subset.load_font(str(HERE / "bootstrap-icons.woff2"), opts)
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(glyphs[n], 16) for n in names])
sub.subset(font)
OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
subset.save_font(font, str(OUT_FONT), opts)
ver = hashlib.md5(OUT_FONT.read_bytes()).hexdigest()[:12]

header = full_css[: full_css.index("*/") + 2]
base = re.search(r"\.bi::before,[^}]+\}", full_css).group(0)
rules = "".join(f'.bi-{n}::before{{content:"\\{glyphs[n]}"}}' for n in names)
OUT_CSS.write_text(
    f"{header}\n/* subset {len(names)} icons — generated by tools/bootstrap-icons/subset.py, อย่าแก้มือ */\n"
    f'@font-face{{font-display:block;font-family:bootstrap-icons;src:url("fonts/bootstrap-icons.woff2?{ver}") format("woff2")}}'
    f"{base}{rules}\n",
    encoding="utf-8",
)
print(f"{len(names)} icons: {' '.join(names)}")
print(f"css {OUT_CSS.stat().st_size} B, woff2 {OUT_FONT.stat().st_size} B")
